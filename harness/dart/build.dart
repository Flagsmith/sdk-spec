// Generates the Dart harness entrypoint for a steps file. See README.md.
//
// Usage: dart build.dart -o path/to/harness_main.dart path/to/steps.dart
//
// Dart cannot call a function by name at runtime, so this finds the marked functions in the steps
// file and generates an entrypoint that passes them to harness.dart. Compile or run the entrypoint
// in the SDK's package, so that the steps file's `package:` imports resolve.
import 'dart:convert';
import 'dart:io';

final _marker = RegExp(r'^\s*//+\s*(When .+?|Create the SDK client.*?)\s*$');
// A top-level function declaration: an optional return type, then the name and its parameters.
final _function = RegExp(
  r'^(?:[\w$][\w$<>?,.\[\] ]*\s)?([A-Za-z_$][\w$]*)\s*(?:<[^()]*>)?\s*\(',
);
final _notFunction = RegExp(
  r'^(?:import|export|part|library|class|mixin|enum|extension|typedef|final|const|var|late)\b',
);

void main(List<String> arguments) {
  if (arguments.length != 3 || arguments[0] != '-o') {
    stderr.writeln('usage: dart build.dart -o <entrypoint> <steps file>');
    exit(64);
  }
  final entrypoint = File(arguments[1]).absolute;
  final stepsFile = File(arguments[2]).absolute;

  final steps = findSteps(stepsFile);
  final harness = Platform.script.resolve('harness.dart');
  entrypoint.writeAsStringSync('''
// Generated by build.dart from ${stepsFile.path}. Do not edit.
import ${_quote('$harness')} as harness;
import ${_quote('${stepsFile.uri}')} as steps;

void main() => harness.run({
${steps.entries.map((s) => '  ${_quote(s.key)}: steps.${s.value},').join('\n')}
});
''');
  for (final MapEntry(key: text, value: function) in steps.entries) {
    stderr.writeln('$text -> $function');
  }
}

/// Returns the steps marked in the file, in order: a marker comment marks the first top-level
/// function after it.
Map<String, String> findSteps(File file) {
  final steps = <String, String>{};
  String? pending;
  final lines = file.readAsLinesSync();
  for (final (index, line) in lines.indexed) {
    if (_marker.firstMatch(line) case final marker?) {
      pending = marker[1];
    } else if (pending != null && !_notFunction.hasMatch(line)) {
      if (_function.firstMatch(line) case final function?) {
        final name = function[1]!;
        if (name.startsWith('_')) {
          stderr.writeln(
            '${file.path}:${index + 1}: step "$pending" must be a public function, '
            'not $name',
          );
          exit(1);
        }
        steps[pending] = name;
        pending = null;
      }
    }
  }
  return steps;
}

String _quote(String value) => jsonEncode(value).replaceAll(r'$', r'\$');
