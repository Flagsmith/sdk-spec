//go:build ignore

// Builds the Go harness for a steps file. See README.md.
//
// Usage: go run build.go -o /harness path/to/steps.go
//
// Go cannot call a function by name at runtime, so this finds the marked functions in the steps
// file, generates a table of them, and compiles it with harness.go into a single binary.
package main

import (
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"runtime"
	"sort"
	"strconv"
	"strings"
)

var (
	marker = regexp.MustCompile(`^//\s*(When .+?|Create the SDK client.*?)\s*$`)
	module = regexp.MustCompile(`(?m)^module\s+(\S+)`)
)

type step struct {
	text     string
	function string
}

func main() {
	output := flag.String("o", "harness", "path of the harness binary to build")
	flag.Parse()
	if flag.NArg() != 1 {
		log.Fatal("usage: go run build.go -o <harness binary> <steps file>")
	}
	stepsFile, err := filepath.Abs(flag.Arg(0))
	check(err)
	binary, err := filepath.Abs(*output)
	check(err)

	steps := findSteps(stepsFile)
	importPath := packageImportPath(filepath.Dir(stepsFile))

	// Build in a temporary package next to the steps file, so it uses the steps file's go.mod.
	// The leading underscore keeps it out of `./...`.
	dir, err := os.MkdirTemp(filepath.Dir(stepsFile), "_harness")
	check(err)
	defer os.RemoveAll(dir)

	_, self, _, _ := runtime.Caller(0)
	harness, err := os.ReadFile(filepath.Join(filepath.Dir(self), "harness.go"))
	check(err)
	check(os.WriteFile(filepath.Join(dir, "harness.go"), harness, 0o644))
	check(os.WriteFile(filepath.Join(dir, "steps.go"), []byte(generate(steps, importPath)), 0o644))

	build := exec.Command("go", "build", "-trimpath", "-o", binary, ".")
	build.Dir = dir
	build.Stdout, build.Stderr = os.Stderr, os.Stderr
	build.Env = append(os.Environ(), "CGO_ENABLED=0")
	if err := build.Run(); err != nil {
		os.RemoveAll(dir)
		log.Fatalf("building the harness: %v", err)
	}
	for _, s := range steps {
		fmt.Fprintf(os.Stderr, "%s -> %s\n", s.text, s.function)
	}
}

// findSteps returns the steps marked in the file, in order: a marker comment marks the first
// function after it.
func findSteps(path string) []step {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
	check(err)

	type event struct {
		pos      token.Pos
		marker   string
		function *ast.FuncDecl
	}
	var events []event
	for _, group := range file.Comments {
		for _, comment := range group.List {
			if m := marker.FindStringSubmatch(comment.Text); m != nil {
				events = append(events, event{pos: comment.Pos(), marker: m[1]})
			}
		}
	}
	for _, decl := range file.Decls {
		if function, ok := decl.(*ast.FuncDecl); ok {
			events = append(events, event{pos: function.Pos(), function: function})
		}
	}
	sort.Slice(events, func(i, j int) bool { return events[i].pos < events[j].pos })

	var steps []step
	pending := ""
	for _, e := range events {
		if e.marker != "" {
			pending = e.marker
		} else if pending != "" {
			name := e.function.Name.Name
			if e.function.Recv != nil || !ast.IsExported(name) {
				log.Fatalf("%s: step %q must be an exported function, not %s", fset.Position(e.pos), pending, name)
			}
			steps = append(steps, step{text: pending, function: name})
			pending = ""
		}
	}
	return steps
}

// packageImportPath returns the import path of the package in dir, from the nearest go.mod.
func packageImportPath(dir string) string {
	for root := dir; ; root = filepath.Dir(root) {
		if goMod, err := os.ReadFile(filepath.Join(root, "go.mod")); err == nil {
			m := module.FindSubmatch(goMod)
			if m == nil {
				log.Fatalf("%s/go.mod has no module line", root)
			}
			relative, err := filepath.Rel(root, dir)
			check(err)
			return strings.TrimSuffix(string(m[1])+"/"+filepath.ToSlash(relative), "/.")
		}
		if filepath.Dir(root) == root {
			log.Fatalf("no go.mod found for %s", dir)
		}
	}
}

func generate(steps []step, importPath string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by build.go. DO NOT EDIT.\n\npackage main\n\n")
	fmt.Fprintf(&b, "import stepsfile %s\n\n", strconv.Quote(importPath))
	b.WriteString("var steps = map[string]any{\n")
	for _, s := range steps {
		fmt.Fprintf(&b, "\t%s: stepsfile.%s,\n", strconv.Quote(s.text), s.function)
	}
	b.WriteString("}\n\nvar stepNames = []string{\n")
	for _, s := range steps {
		fmt.Fprintf(&b, "\t%s,\n", strconv.Quote(s.text))
	}
	b.WriteString("}\n")
	return b.String()
}

func check(err error) {
	if err != nil {
		log.Fatal(err)
	}
}
